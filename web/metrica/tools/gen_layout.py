#!/usr/bin/env python3
"""Generate layout.css: every component, illustration, arrow, button and text line placed at its
measured reference coordinates. Units are native reference pixels; at run time
--n = 1 native px of the component (100cqw / crop width), so each component scales as one drawing.
Text sizes/offsets come from tools/text_fit.json (written by tools/fit_text.js) when present."""
import json
import pathlib

import numpy as np
from PIL import Image

HERE = pathlib.Path(__file__).resolve().parent.parent
SPEC = json.loads((HERE / "tools/layout_spec.json").read_text())
FIT_P = HERE / "tools/text_fit.json"
FIT = json.loads(FIT_P.read_text()) if FIT_P.exists() else {}


DECOR = json.loads((HERE / "decor/meta.json").read_text())


def meta(name):
    return DECOR[name]


def alpha_bbox(src):
    a = np.array(Image.open(HERE / "assets" / f"{src}.png").getchannel("A"))
    ys, xs = np.where(a > 16)
    return a.shape[1], a.shape[0], xs.min(), ys.min(), xs.max() + 1, ys.max() + 1


f = lambda v: f"{v:.2f}".rstrip("0").rstrip(".")
css = ["/* generated by tools/gen_layout.py - do not edit by hand */"]
comps = {}
for sec, s in SPEC["sections"].items():
    W, H = s["w"], s["h"]
    css.append(f".mtr-sec--{sec} .mtr-stage{{aspect-ratio:{W}/{H}}}")
for name in sorted(DECOR):
    m = meta(name)
    comps[name] = m
    if name.startswith("bg-"):
        continue
    sec = "tools" if name in ("sub",) or name.startswith("tool-") else "why"
    W, H = SPEC["sections"][sec]["w"], SPEC["sections"][sec]["h"]
    x0, y0, x1, y1 = m["crop"]
    css.append(f'.mtr-c[data-c="{name}"]{{--cw:{m["w"]};aspect-ratio:{m["w"]}/{m["h"]};'
               f'--mx:{f(x0 / W * 100)}%;--my:{f(y0 / H * 100)}%;--mw:{f(m["w"] / W * 100)}%}}')


def local(comp, box, inside=None):
    """Native box relative to the component crop (or to a positioned box inside it)."""
    cx0, cy0 = comps[comp]["crop"][:2]
    if inside:
        bx0, by0 = SPEC["boxes"][inside]["box"][:2]
        return [box[0] - bx0, box[1] - by0, box[2] - bx0, box[3] - by0]
    return [box[0] - cx0, box[1] - cy0, box[2] - cx0, box[3] - cy0]


for k, a in SPEC["art"].items():
    PW, PH, bx0, by0, bx1, by1 = alpha_bbox(a["src"])
    tx0, ty0, tx1, ty1 = local(a["comp"], a["box"])
    s = min((tx1 - tx0) / (bx1 - bx0), (ty1 - ty0) / (by1 - by0))
    left = (tx0 + tx1) / 2 - (bx0 + bx1) / 2 * s
    top = (ty0 + ty1) / 2 - (by0 + by1) / 2 * s
    css.append(f"#{k}{{left:calc({f(left)}*var(--n));top:calc({f(top)}*var(--n));width:calc({f(PW * s)}*var(--n))}}")

for k, b in SPEC["boxes"].items():
    if k.startswith("i-"):
        continue  # icons are part of the decoration
    x0, y0, x1, y1 = local(b["comp"], b["box"], b.get("in"))
    css.append(f"#{k}{{left:calc({f(x0)}*var(--n));top:calc({f(y0)}*var(--n));width:calc({f(x1 - x0)}*var(--n));height:calc({f(y1 - y0)}*var(--n))}}")


used = {}
for k, t in SPEC["texts"].items():
    lines = [local(t["comp"], l, t.get("in")) for l in t["lines"]]
    cw = (SPEC["boxes"][t["in"]]["box"][2] - SPEC["boxes"][t["in"]]["box"][0]) if t.get("in") else comps[t["comp"]]["w"]
    h0 = lines[0][3] - lines[0][1]
    fit = FIT.get(k, {})
    fs = fit.get("fs", h0 * 0.8)
    lh = fit.get("lh", (lines[1][1] - lines[0][1]) if len(lines) > 1 else fs * 1.5)
    top = fit.get("t", lines[0][1] - (lh - h0) / 2)
    if t.get("align") == "center":
        cx = fit.get("cx", sum((l[0] + l[2]) / 2 for l in lines) / len(lines))
        pos = f"left:calc({f(cx)}*var(--n));translate:-50% 0;text-align:center"
        used[k] = {"fs": fs, "lh": lh, "t": top, "cx": cx}
    else:
        r = fit.get("r", cw - max(l[2] for l in lines))
        pos = f"right:calc({f(r)}*var(--n));text-align:right"
        used[k] = {"fs": fs, "lh": lh, "t": top, "r": r}
    css.append(f"#{k}{{{pos};top:calc({f(top)}*var(--n));font-size:calc({f(fs)}*var(--n));line-height:calc({f(lh)}*var(--n))}}")

(HERE / "tools/text_vars.json").write_text(json.dumps(used, indent=1))
(HERE / "layout.css").write_text("\n".join(css) + "\n", encoding="utf-8")
print(f"layout.css: {len(css)} rules")
